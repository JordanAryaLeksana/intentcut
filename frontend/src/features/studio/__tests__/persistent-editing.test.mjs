import {renderToStaticMarkup} from "react-dom/server";
import {createRequire} from "node:module";
const require=createRequire(import.meta.url);
const {QueryClient,QueryClientProvider}=require("@tanstack/react-query");
import {useDraftStore,draftMatchesSaved} from "../store/use-draft-store.ts";
import {RenderVersionPicker} from "../draft-persistence.tsx";
import {renderVersionsKey,renderVersionsOptions} from "../use-editing.ts";
import {getSavedDraft,saveDraft,renderDraft,parseSavedDraft} from "../../../lib/api/editing.ts";
const project="f93aa0e0-4ada-463c-a7c5-086ddeecd4b9";
const job="44c3fa22-3ee4-43ec-a476-3e99172c9af2";
const artifact="b43e8613-09a4-4187-98f1-ad23d5653c09";
const fixture=JSON.parse(readFileSync(new URL("./published-storyboard.json",import.meta.url)));
const saved={revision:3,base_job_id:job,base_artifact_id:artifact,window_indices:[6,2,4,8],updated_at:"2026-10-30T00:00:00Z",storyboard:fixture};
const store=()=>useDraftStore.getState();
const originalFetch=globalThis.fetch;
function reset(){useDraftStore.setState({byProject:{},savedByProject:{},restoredByProject:{},previewByProject:{}});process.env.NEXT_PUBLIC_API_BASE_URL="http://127.0.0.1:8011";}
afterEach(()=>{globalThis.fetch=originalFetch;});

test("reload restores persisted reordered/removed cuts and the server revision",()=>{ reset();
  store().restore(project,parseSavedDraft(saved));
  const draft=store().byProject[project];
  assert.deepEqual(draft.cuts.map(c=>c.window_index),[6,2,4,8]);
  assert.equal(draftMatchesSaved(draft,store().savedByProject[project]),true);
  assert.equal(store().savedByProject[project].revision,3);
  assert.equal(draft.past.length,0);
  assert.equal(store().byProject.other,undefined);
});
test("save completion cannot erase edits made while request was pending",()=>{ reset();
  store().restore(project,saved);
  const id=store().byProject[project].cuts[0].id;
  store().move(project,id,1);
  store().saved(project,{...saved,revision:4});
  assert.equal(draftMatchesSaved(store().byProject[project],store().savedByProject[project]),false);
  const edited=store().byProject[project];
  store().restore(project,{...saved,revision:5});
  assert.equal(store().byProject[project],edited);
  store().restore(project,{...saved,revision:5},true);
  assert.equal(draftMatchesSaved(store().byProject[project],store().savedByProject[project]),true);
});
test("save/load/admit use exact scoped contracts with no client media paths",async()=>{ reset();
  const requests=[];
  globalThis.fetch=async(url,options)=>{requests.push({url,...options});return Response.json(options.method==="PUT"?saved:options.method==="POST"?{id:job}:{draft:saved});};
  assert.equal((await getSavedDraft(project)).revision,3);
  await saveDraft(project,{expected_revision:2,base_job_id:job,base_artifact_id:artifact,window_indices:[6,2,4,8]});
  assert.equal(await renderDraft(project,3),job);
  assert.deepEqual(requests.map(r=>r.method??"GET"),["GET","PUT","POST"]);
  assert.deepEqual(JSON.parse(requests[2].body),{revision:3});
  assert.ok(requests.every(r=>r.url.includes(`/projects/${project}/edit-draft`)));
  assert.doesNotMatch(requests[1].body,/source_path|start_seconds|end_seconds/);
});
test("409 conflict is surfaced without mutating local state",async()=>{ reset();
  store().restore(project,saved);const draft=store().byProject[project];
  globalThis.fetch=async()=>Response.json({code:"draft_conflict",message:"Draft changed"},{status:409});
  await assert.rejects(()=>saveDraft(project,{expected_revision:2,base_job_id:job,base_artifact_id:artifact,window_indices:[]}),e=>e.status===409);
  assert.equal(store().byProject[project],draft);
});
test("invalid and duplicate saved references are rejected before restore",()=>{ reset();
  assert.throws(()=>parseSavedDraft({...saved,window_indices:[999]}));
  assert.throws(()=>parseSavedDraft({...saved,window_indices:[2,2]}));
  assert.throws(()=>parseSavedDraft({...saved,base_job_id:"../other"}));
});
test("render versions poll only active jobs and allow selecting historical output",()=>{ reset();
  const c=new QueryClient({defaultOptions:{queries:{retry:false,gcTime:Infinity}}});
  const older="11111111-1111-4111-8111-111111111111";
  c.setQueryData(renderVersionsKey(project),[{job_id:job,revision:3,status:"succeeded"},{job_id:older,revision:2,status:"succeeded"}]);
  const html=renderToStaticMarkup(createElement(QueryClientProvider,{client:c},createElement(RenderVersionPicker,{projectId:project})));
  assert.match(html,/Original AI first cut/);assert.match(html,/Draft revision 3/);assert.match(html,/Draft revision 2/);
  store().setPreview(project,older);assert.equal(store().previewByProject[project],older);
  store().setPreview(project,null);assert.equal(store().previewByProject[project],null);
  const options=renderVersionsOptions(project);
  assert.equal(options.refetchInterval({state:{data:[{status:"running"}],error:null}}),2000);
  assert.equal(options.refetchInterval({state:{data:[{status:"succeeded"}],error:null}}),false);
  c.clear();
});
